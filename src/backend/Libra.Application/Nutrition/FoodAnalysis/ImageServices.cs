namespace Libra.Application.Nutrition.FoodAnalysis;

/// <summary>The outcome of validating and normalizing an uploaded picture.</summary>
public sealed record ProcessedImage(byte[] Bytes, string ContentType, int Width, int Height);

/// <summary>Why a picture was rejected. Each maps to a message the user can act on.</summary>
public enum ImageRejection
{
    Empty,
    TooLarge,
    UnsupportedType,
    Unreadable,
    TooSmall,
    TooManyPixels,
}

public sealed record ImageProcessingResult(ProcessedImage? Image, ImageRejection? Rejection)
{
    public bool IsValid => Image is not null;

    public static ImageProcessingResult Ok(ProcessedImage image) => new(image, null);

    public static ImageProcessingResult Rejected(ImageRejection rejection) => new(null, rejection);
}

/// <summary>
/// Validates the actual bytes (not the declared type), applies the EXIF orientation, resizes to the configured
/// bound and re-encodes without metadata, so no location or device data reaches the provider or the store.
/// </summary>
public interface IFoodImageProcessor
{
    ImageProcessingResult Process(byte[] bytes);
}

/// <summary>
/// Private, owner-scoped byte storage for analysis photos. Keys are generated by the store and are never derived
/// from user input; reads go through the handler, which checks ownership first.
/// </summary>
public interface IImageStore
{
    Task<string> SaveAsync(byte[] bytes, string contentType, CancellationToken cancellationToken);

    Task<byte[]?> ReadAsync(string storageKey, CancellationToken cancellationToken);

    Task DeleteAsync(string storageKey, CancellationToken cancellationToken);
}
